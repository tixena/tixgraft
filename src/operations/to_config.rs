//! Renders the configuration that the arguments describe as the YAML `--to-config` prints.
//!
//! The source is the config file merged with CLI overrides, or the pull arguments alone.

use std::path::Path;

use crate::cli::Args;
use crate::config::Config;
use crate::operations::pull::{build_config_from_args, build_merged_config};
use anyhow::Result;
use os_shim::System;

/// Builds the configuration from the config file when it exists, otherwise from the pull
/// arguments, validates it and returns it as YAML.
///
/// # Errors
///
/// Returns an error if no source is provided, the configuration is invalid or serialization fails.
#[inline]
pub fn generate_yaml_config(args: &Args, system: &dyn System) -> Result<String> {
    let config = if Path::new(&args.config).exists() {
        build_merged_config(args, system)?
    } else if !args.pulls.sources.is_empty() {
        build_config_from_args(args)?
    } else {
        return Err(anyhow::anyhow!(
            "No configuration source provided. Specify --config or provide pull arguments."
        ));
    };

    config.validate(system)?;

    serialize_config(&config)
}

/// Serializes the configuration to YAML under the generated-file comment lines.
fn serialize_config(config: &Config) -> Result<String> {
    let yaml = serde_saphyr::to_string(config)
        .map_err(|err| anyhow::anyhow!("Failed to serialize config to YAML: {err}"))?;

    let formatted = format_yaml_output(&yaml);

    Ok(formatted)
}

/// Prefixes the two generated-file comment lines and guarantees a trailing newline.
fn format_yaml_output(yaml: &str) -> String {
    let mut output = String::from("# Generated by tixgraft --to-config\n");
    output.push_str("# https://github.com/tixena/tixgraft\n\n");

    output.push_str(yaml);

    if !output.ends_with('\n') {
        output.push('\n');
    }

    output
}

